import assert from 'node:assert/strict';
import {blankData,dateKey} from '../web/core.mjs';
import {elapsedSession,sessionRecord} from '../web/focus-planning.mjs';
import {validTimer,validFocusData} from '../web/focus-model.mjs';
import {timerWindowView} from '../web/focus-timer-window.mjs';
import {shared,validShared,keyMaterial,encryptShared,decryptShared} from '../web/focus-sync-model.mjs';
import {portableZip,decodeBackup} from '../web/focus-portable.mjs';
import {unzipSync,strFromU8} from '../web/vendor/fflate.mjs';

const start=Date.now()-60*60000,s={id:'continued',title:'制作 · 練習',date:dateKey(),start:'00:00',startedAt:new Date(start).toISOString(),mode:'timer',goal:25*60000,elapsed:0,started:start,running:true};
assert.equal(elapsedSession(s,start+25*60000),1500000);
assert.equal(timerWindowView(s,start+25*60000).text,'00:25:00');
assert.equal(timerWindowView(s,start+25*60000+999).extraText,'+00:00:00');
assert.equal(timerWindowView(s,start+25*60000+1000).extraText,'+00:00:01');
const finishAt=start+28*60000+12000,log=sessionRecord(s,finishAt);
assert.equal(log.elapsedSeconds,1692);assert.equal(log.minutes,28);
assert.equal(log.endedAt,new Date(finishAt).toISOString());assert.equal(log.timerGoalMinutes,25);
assert.equal(log.title,s.title);assert.equal(log.note,'');assert(!Object.keys(log).some(k=>/over(time|run)/i.test(k)));
const paused={...s,elapsed:1692000,started:finishAt,pausedAt:new Date(finishAt).toISOString(),running:false};
assert(validTimer(paused));assert.equal(elapsedSession(paused,finishAt+120000),1692000);
assert.equal(sessionRecord(paused,finishAt+120000).endedAt,paused.pausedAt);
const resumed={...paused,started:finishAt+120000,running:true,pausedAt:undefined};
assert.equal(sessionRecord(resumed,finishAt+168000).elapsedSeconds,1740);
assert.equal(sessionRecord({...s,program:'pomodoro'},finishAt).elapsedSeconds,1692);
assert.equal(sessionRecord(s,finishAt).id,sessionRecord(s,finishAt+10000).id);
const data=blankData();data.logs.push(log);assert(validFocusData(data));
const asset=shared(data,[],paused);assert(validShared(asset));
const {key}=await keyMaterial('A'.repeat(43));assert.deepEqual(await decryptShared(await encryptShared(asset,key),key),JSON.parse(JSON.stringify(asset)));
const backup={format:'focus-device',version:1,data,config:{template:'focus',order:['capture','plan','progress','logs'],progress:'calendar',routines:[]},timer:paused};
assert.equal(decodeBackup(JSON.parse(JSON.stringify(backup))).data.logs[0].elapsedSeconds,1692);
const files=unzipSync(portableZip(backup)),csv=strFromU8(files['records.csv']);
assert(csv.includes('1692'));assert(!csv.includes('超過'));assert(!/over(time|run)/i.test(csv));
assert(!validTimer({...paused,elapsed:-1}));assert(!validTimer({...paused,elapsed:1.5}));
console.log('Continued timer checks passed: boundary, exact total seconds/endpoints, pause/resume, pomodoro, stable IDs, validation, encrypted sync and portable export.');
